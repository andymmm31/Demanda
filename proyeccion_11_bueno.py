def guardar_modelo_y_metricas(modelo, metricas, forecast, params, regresores,
                            umbral_corr, growth_type, id_datos=None):
    """
    Guarda el modelo y sus métricas para futuras ejecuciones

    Args:
        modelo: Modelo entrenado
        metricas: Diccionario con métricas de rendimiento
        forecast: DataFrame con pronóstico
        params: Hiperparámetros del modelo
        regresores: Lista de regresores utilizados
        umbral_corr: Umbral de correlación utilizado
        growth_type: Tipo de crecimiento utilizado
        id_datos: Identificador único del conjunto de datos
    """
    if not os.path.exists('modelos_guardados'): os.makedirs('modelos_guardados')
    now_str = datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')
    timestamp = datetime.datetime.now().strftime('%Y%m%d%H%M%S')

    modelo_actual_info = {
        'fecha_creacion': now_str, 'metricas': metricas, 'forecast': forecast, 'parametros': params,
        'configuracion': {'regresores': regresores, 'umbral_correlacion': umbral_corr, 'growth_type': growth_type},
        'id_datos': id_datos
    }
    try: modelo_actual_info['modelo_serializado'] = pickle.dumps(modelo)
    except Exception as e: print(f"No se pudo serializar el modelo: {str(e)}"); modelo_actual_info['modelo_serializado'] = None

    ruta_modelo_actual = f'modelos_guardados/modelo_info_{id_datos}_{timestamp}.pkl' if id_datos else f'modelos_guardados/modelo_info_{timestamp}.pkl'
    with open(ruta_modelo_actual, 'wb') as file: pickle.dump(modelo_actual_info, file)
