    """
    Refina la búsqueda de hiperparámetros basándose en el mejor modelo anterior

    Args:
        mejor_modelo_anterior: Información del mejor modelo anterior
        df_actual: DataFrame actual para comparar características

    Returns:
        dict: Grid de parámetros refinado o None
    """
    if mejor_modelo_anterior is None or 'parametros' not in mejor_modelo_anterior: return None
    params_ant = mejor_modelo_anterior['parametros']
    param_grid_refinado = {}
    if 'changepoint_prior_scale' in params_ant: v_ant = params_ant['changepoint_prior_scale']; param_grid_refinado['changepoint_prior_scale'] = [max(0.001,v_ant*0.5), v_ant, min(0.5,v_ant*2)]
