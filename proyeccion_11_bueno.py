def combinar_prophet_rnn(forecast_prophet, predicciones_rnn, fechas_futuras, peso_rnn=0.5):
    """
    Combinar predicciones de Prophet y redes neuronales de manera robusta

    Args:
        forecast_prophet: DataFrame con pronóstico de Prophet
        predicciones_rnn: Array con predicciones de RNN
        fechas_futuras: Array con fechas futuras
        peso_rnn: Peso dado a las predicciones de RNN (0-1)

    Returns:
        DataFrame: DataFrame con pronóstico combinado
    """
    min_len = min(len(fechas_futuras), len(predicciones_rnn), len(forecast_prophet))
    print(f"Combinando predicciones con longitud mínima: {min_len}")
    fechas_futuras, predicciones_rnn = fechas_futuras[:min_len], predicciones_rnn[:min_len]
    if isinstance(forecast_prophet, pd.DataFrame):
        forecast_prophet = forecast_prophet.iloc[:min_len].copy()
        try:
            fc_comb = pd.DataFrame({'ds':fechas_futuras, 'yhat_prophet':forecast_prophet['yhat'].values, 'yhat_rnn':predicciones_rnn})
            fc_comb['yhat'] = (1-peso_rnn)*fc_comb['yhat_prophet'] + peso_rnn*fc_comb['yhat_rnn']
            if 'yhat_lower' in forecast_prophet.columns and 'yhat_upper' in forecast_prophet.columns:
                fc_comb['yhat_lower'], fc_comb['yhat_upper'] = forecast_prophet['yhat_lower'].values, forecast_prophet['yhat_upper'].values
            return fc_comb
        except Exception as e:
            print(f"Error al combinar prophet_rnn: {e}")
            return pd.DataFrame({'ds':fechas_futuras, 'yhat':predicciones_rnn, 'yhat_prophet':forecast_prophet['yhat'].values if 'yhat' in forecast_prophet.columns else np.zeros(min_len), 'yhat_rnn':predicciones_rnn})
    else:
        print("Advertencia: forecast_prophet no es DataFrame")
        return pd.DataFrame({'ds':fechas_futuras, 'yhat':predicciones_rnn, 'yhat_rnn':predicciones_rnn})

def crear_ensamble_mixto(forecast_prophet, predicciones_rnn, predicciones_avanzado, predicciones_gbr,
                         fechas_futuras,
                         pesos={'prophet': 0.25, 'rnn': 0.25, 'avanzado': 0.25, 'gbr': 0.25}):
    """
    Crear un ensamble que combine modelos de diferentes familias (Prophet, GRU, WaveNet, GBR).

    Args:
        forecast_prophet: DataFrame con pronóstico de Prophet.
        predicciones_rnn: Array con predicciones de RNN (GRU).
        predicciones_avanzado: Array con predicciones del modelo avanzado (WaveNet).
        predicciones_gbr: Array con predicciones de Gradient Boosting Regressor.
        fechas_futuras: Array con fechas futuras.
        pesos: Diccionario con pesos para cada tipo de modelo.

    Returns:
        DataFrame: DataFrame con pronóstico combinado.
    """
    suma_pesos = sum(pesos.values())
    if abs(suma_pesos - 1.0) > 0.001:
        if suma_pesos == 0: print("Advertencia: Pesos de ensamble son cero. Usando pesos iguales."); pesos = {k:1./len(pesos) for k in pesos.keys()} if pesos else {}
        else: factor = 1./suma_pesos; pesos = {k:v*factor for k,v in pesos.items()}
        print(f"Pesos normalizados: {pesos}")

    lengths = [len(fechas_futuras)]
    if forecast_prophet is not None: lengths.append(len(forecast_prophet))
    if predicciones_rnn is not None: lengths.append(len(predicciones_rnn))
    if predicciones_avanzado is not None: lengths.append(len(predicciones_avanzado))
    if predicciones_gbr is not None: lengths.append(len(predicciones_gbr))
    min_len = min(lengths) if lengths else 0
    print(f"Longitudes: Prophet={len(forecast_prophet) if forecast_prophet is not None else 'N/A'}, RNN={len(predicciones_rnn) if predicciones_rnn is not None else 'N/A'}, WaveNet={len(predicciones_avanzado) if predicciones_avanzado is not None else 'N/A'}, GBR={len(predicciones_gbr) if predicciones_gbr is not None else 'N/A'}, Fechas={len(fechas_futuras)}")
    print(f"Usando longitud mínima para ensamble: {min_len}")
    if min_len == 0:
        print("Advertencia: No hay datos o un modelo no generó predicciones. Ensamble no creado.")
        if forecast_prophet is not None and len(forecast_prophet) > 0:
            df_fb = forecast_prophet[['ds','yhat']].copy()
            if 'yhat_lower' in forecast_prophet: df_fb['yhat_lower'] = forecast_prophet['yhat_lower']
            if 'yhat_upper' in forecast_prophet: df_fb['yhat_upper'] = forecast_prophet['yhat_upper']
            return df_fb
        return pd.DataFrame({'ds':fechas_futuras, 'yhat':np.nan})

    fechas_futuras = fechas_futuras[:min_len]
    yhat_p = forecast_prophet['yhat'].values[:min_len] if forecast_prophet is not None else np.full(min_len, np.nan)
    yhat_l_p = forecast_prophet['yhat_lower'].values[:min_len] if forecast_prophet is not None and 'yhat_lower' in forecast_prophet.columns else np.full(min_len, np.nan)
    yhat_u_p = forecast_prophet['yhat_upper'].values[:min_len] if forecast_prophet is not None and 'yhat_upper' in forecast_prophet.columns else np.full(min_len, np.nan)
    pred_r = predicciones_rnn[:min_len] if predicciones_rnn is not None else np.full(min_len, np.nan)
    pred_a = predicciones_avanzado[:min_len] if predicciones_avanzado is not None else np.full(min_len, np.nan)
    pred_g = predicciones_gbr[:min_len] if predicciones_gbr is not None else np.full(min_len, np.nan)

    try:
        fc_comb_dict = {'ds':fechas_futuras, 'yhat_prophet':yhat_p, 'yhat_rnn':pred_r, 'yhat_avanzado':pred_a, 'yhat_gbr':pred_g}
        fc_comb = pd.DataFrame(fc_comb_dict)
        yhat_comb = np.zeros(min_len); total_w_used = np.zeros(min_len)
        for mkey, mpred_col in [('prophet','yhat_prophet'), ('rnn','yhat_rnn'), ('avanzado','yhat_avanzado'), ('gbr','yhat_gbr')]:
            if pesos.get(mkey,0)>0 and mpred_col in fc_comb.columns: # Check if pred_col exists
                 yhat_comb += np.nan_to_num(pesos[mkey] * fc_comb[mpred_col])
                 total_w_used += np.where(np.isnan(fc_comb[mpred_col]), 0, pesos[mkey])
        fc_comb['yhat'] = np.divide(yhat_comb, total_w_used, out=np.full_like(yhat_comb, np.nan), where=total_w_used!=0)
        fc_comb['yhat_lower'], fc_comb['yhat_upper'] = yhat_l_p, yhat_u_p
        fc_comb['yhat'] = fc_comb['yhat'].clip(lower=0)
        if 'yhat_lower' in fc_comb: fc_comb['yhat_lower'] = fc_comb['yhat_lower'].clip(lower=0)
        if 'yhat_upper' in fc_comb: fc_comb['yhat_upper'] = fc_comb['yhat_upper'].clip(lower=0)
        return fc_comb
    except Exception as e:
        print(f"Error creando DataFrame combinado: {e}")
        if forecast_prophet is not None and len(forecast_prophet) >= min_len:
            df_s = forecast_prophet.iloc[:min_len][['ds','yhat','yhat_lower','yhat_upper']].copy(); print("Fallback: Usando Prophet."); return df_s
        elif predicciones_rnn is not None and len(predicciones_rnn) >= min_len: print("Fallback: Usando RNN."); return pd.DataFrame({'ds':fechas_futuras, 'yhat':pred_r})
        print("Fallback: Devolviendo DataFrame vacío."); return pd.DataFrame({'ds':fechas_futuras, 'yhat':np.nan})

def calcular_metricas_modelo(y_true, y_pred):
    """
    Calcula las métricas de rendimiento para un modelo

    Args:
        y_true: Valores reales
        y_pred: Valores predichos

    Returns:
        dict: Diccionario con métricas de rendimiento
    """
    valid_idx = ~np.isnan(y_true) & ~np.isnan(y_pred)
    y_true_v, y_pred_v = y_true[valid_idx], y_pred[valid_idx]
    if len(y_true_v) == 0: return {'RMSE':np.nan, 'MAE':np.nan, 'R2':np.nan, 'MAPE':np.nan}
    rmse, mae, r2 = np.sqrt(mean_squared_error(y_true_v,y_pred_v)), mean_absolute_error(y_true_v,y_pred_v), r2_score(y_true_v,y_pred_v)
    try: mape = mean_absolute_percentage_error(y_true_v,y_pred_v)
    except: mape = np.nan
    return {'RMSE':rmse, 'MAE':mae, 'R2':r2, 'MAPE':mape}

