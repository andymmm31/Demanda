def detectar_frecuencia_datos(df):
    """
    Detecta automáticamente la frecuencia de los datos (mensual, diario, horario)

    Args:
        df: DataFrame con los datos y columna 'Date'

    Returns:
        str: Frecuencia detectada ('mensual', 'diario', 'horario')
    """
    if len(df) < 2:
        return 'desconocida'

    df_temp = df.sort_values('Date').copy()
    diff_dates = df_temp['Date'].diff()[1:]
    diff_seconds_median = diff_dates.dt.total_seconds().median()

    umbral_horario = 60 * 60 * 3
    umbral_diario = 60 * 60 * 24 * 3
    umbral_mensual = 60 * 60 * 24 * 35

    if diff_seconds_median <= umbral_horario:
        if abs(diff_seconds_median - 3600) < 900:
            return 'horario'
        else:
            return 'sub-horario'
    elif diff_seconds_median <= umbral_diario:
        if abs(diff_seconds_median - 86400) < 14400:
            return 'diario'
        else:
            return 'sub-diario'
    elif diff_seconds_median <= umbral_mensual:
        return 'mensual'
    else:
        return 'superior a mensual'

