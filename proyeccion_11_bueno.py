def traducir_periodos_a_texto(periodos, frecuencia):
    """
    Traduce un número de periodos a una descripción textual según la frecuencia

    Args:
        periodos: Número de periodos
        frecuencia: Frecuencia de los datos ('mensual', 'diario', 'horario', etc.)

    Returns:
        str: Descripción textual
    """
    if frecuencia == 'mensual':
        años = periodos / 12
        return f"{int(años)} años" if años.is_integer() else f"{años:.1f} años"
    elif frecuencia == 'diario':
        if periodos < 30: return f"{periodos} días"
        meses = periodos / 30.44
        return f"{meses:.1f} meses" if meses < 12 else f"{meses/12:.1f} años"
    elif frecuencia in ['horario', 'sub-horario']:
        if periodos < 24: return f"{periodos} horas"
        días = periodos / 24
        return f"{días:.1f} días" if días < 7 else f"{días/7:.1f} semanas"
    else:
        return f"{periodos} periodos"

