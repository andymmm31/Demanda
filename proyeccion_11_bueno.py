    growth_type = growth_input if growth_input in ['linear', 'logistic'] else 'logistic'

    respuesta_ajuste = input("Aplicar ajustes adicionales a Prophet? (s/n, default: s): ").lower()
    ajuste_adicional_prophet = respuesta_ajuste != 'n'

