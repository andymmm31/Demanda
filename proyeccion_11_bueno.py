def entrenar_modelo_prophet(df, regresores=None, growth_type='logistic', eventos=None, params=None,
                         periodos_futuros=120, vis_componentes=True, ajuste_adicional=True, frecuencia='mensual'):
    """
    Entrena un modelo Prophet con los parámetros especificados y mejoras adicionales
    Adaptado para diferentes frecuencias de datos
    """
    if params is None:
        params = {'changepoint_prior_scale': 0.01, 'seasonality_prior_scale': 10.0,
                  'holidays_prior_scale': 10.0, 'seasonality_mode': 'additive', 'changepoint_range': 0.8}
    freq_prophet = obtener_freq_prophet(frecuencia)
    model = Prophet(
        changepoint_prior_scale=params.get('changepoint_prior_scale', 0.01),
        seasonality_prior_scale=params.get('seasonality_prior_scale', 10.0),
        holidays_prior_scale=params.get('holidays_prior_scale', 10.0),
        seasonality_mode=params.get('seasonality_mode', 'additive'),
        changepoint_range=params.get('changepoint_range', 0.8),
        growth=growth_type,
        daily_seasonality=frecuencia in ['horario', 'sub-horario', 'diario', 'sub-diario'],
        weekly_seasonality=frecuencia in ['diario', 'sub-diario']
    )
    if growth_type == 'logistic' and 'cap' not in df.columns:
        cap = df['y'].quantile(0.95) * 2; df['cap'] = cap
        print(f"Capacidad para logístico: {cap:.2f}")
    if regresores:
        for r in regresores:
            if r in df.columns: model.add_regressor(r)
    if frecuencia == 'mensual': model.add_seasonality(name='yearly', period=365.25, fourier_order=10)
    elif frecuencia == 'diario': model.add_seasonality(name='yearly', period=365.25, fourier_order=10); model.add_seasonality(name='weekly', period=7, fourier_order=3)
    elif frecuencia in ['horario', 'sub-horario']: model.add_seasonality(name='yearly', period=365.25, fourier_order=10); model.add_seasonality(name='weekly', period=7, fourier_order=3); model.add_seasonality(name='daily', period=1, fourier_order=6)
    if eventos is not None: model.holidays = eventos

    print("\nEntrenando modelo Prophet final..."); model.fit(df)
    forecast_train = model.predict(df)
    y_true, y_pred = df['y'], forecast_train['yhat']
    rmse, mae, r2, mape = np.sqrt(mean_squared_error(y_true, y_pred)), mean_absolute_error(y_true, y_pred), r2_score(y_true, y_pred), mean_absolute_percentage_error(y_true, y_pred)

    print(f"\nGenerando pronóstico para {periodos_futuros} períodos futuros...")
    future = model.make_future_dataframe(periods=periodos_futuros, freq=freq_prophet)
    if growth_type == 'logistic': future['cap'] = df['cap'].max() if 'cap' in df.columns else df['y'].quantile(0.95) * 2
    if regresores:
        for r in regresores:
            if r in df.columns:
                p_avg = 12 if frecuencia == 'mensual' else 30 if frecuencia == 'diario' else 24*7 if frecuencia in ['horario', 'sub-horario'] else max(1, len(df) // 10)
                last_val = df[r].rolling(window=p_avg).mean().iloc[-1] if len(df) >= p_avg else df[r].mean()
                future[r] = future['ds'].map(lambda x: last_val if x > df['ds'].max() else (df.loc[df['ds'] == x, r].iloc[0] if x in df['ds'].values else np.nan))
                future[r] = future[r].interpolate(method='linear').fillna(last_val)
    forecast = model.predict(future)

    if ajuste_adicional:
        print("Aplicando ajustes adicionales...");
        p_adj = 12 if frecuencia == 'mensual' else 30 if frecuencia == 'diario' else 24*7 if frecuencia in ['horario', 'sub-horario'] else max(1, len(df) // 10)
        if len(df) >= p_adj*2:
            r_true, r_pred = df['y'].iloc[-p_adj:].values, forecast_train['yhat'].iloc[-p_adj:].values
            adj_factor = np.median(r_true / (r_pred + 1e-10))
            if 0.8 <= adj_factor <= 1.2:
                print(f"Factor de ajuste: {adj_factor:.3f}")
                future_idx = forecast['ds'] > df['ds'].max()
                for col in ['yhat', 'yhat_lower', 'yhat_upper']:
                    if col in forecast.columns: forecast.loc[future_idx, col] *= adj_factor
    for col in ['yhat', 'yhat_lower', 'yhat_upper']:
        if col in forecast.columns: forecast[col] = forecast[col].clip(lower=0)

    if vis_componentes: model.plot_components(forecast); plt.tight_layout(); plt.show()
    plt.figure(figsize=(15, 8)); model.plot(forecast, uncertainty=True); plt.title('Pronóstico con Prophet'); plt.ylabel('Energía'); plt.legend(['Histórico', 'Pronóstico', 'IC']); plt.grid(True); plt.tight_layout(); plt.show()
    plt.figure(figsize=(15, 6)); plt.plot(df['ds'], df['y'], 'ko', markersize=4, label='Reales'); plt.plot(forecast_train['ds'], forecast_train['yhat'], 'b-', label='Ajuste'); plt.fill_between(forecast_train['ds'], forecast_train['yhat_lower'], forecast_train['yhat_upper'], color='blue', alpha=0.2); plt.title('Ajuste vs Reales'); plt.xlabel('Fecha'); plt.ylabel('Energía'); plt.legend(); plt.grid(True); plt.tight_layout(); plt.show()

    print(f"\nMétricas: RMSE: {rmse:.4f}, MAE: {mae:.4f}, R²: {r2:.4f}, MAPE: {mape:.2f}%")
    metricas_dict = {'RMSE': rmse, 'MAE': mae, 'R2': r2, 'MAPE': mape}
    return model, forecast, metricas_dict

def optimizar_hiperparametros(df, regresores=None, growth_type='logistic', eventos=None):
    """
    Optimiza los hiperparámetros de Prophet sin mostrar visualizaciones intermedias
    """
    print("\nIniciando optimización de hiperparámetros por etapas...")
    def entrenar_prophet_silencioso(df_in, regresores_in, growth_in, eventos_in, params_in):
        if params_in is None: params_in = {'changepoint_prior_scale': 0.01, 'seasonality_prior_scale': 10.0, 'holidays_prior_scale': 10.0, 'seasonality_mode': 'additive', 'changepoint_range': 0.8}
        model = Prophet(changepoint_prior_scale=params_in.get('changepoint_prior_scale',0.01), seasonality_prior_scale=params_in.get('seasonality_prior_scale',10.0), holidays_prior_scale=params_in.get('holidays_prior_scale',10.0), seasonality_mode=params_in.get('seasonality_mode','additive'), changepoint_range=params_in.get('changepoint_range',0.8), growth=growth_in, daily_seasonality=False, weekly_seasonality=False)
        if growth_in == 'logistic' and 'cap' not in df_in.columns: df_in['cap'] = df_in['y'].quantile(0.95) * 2
