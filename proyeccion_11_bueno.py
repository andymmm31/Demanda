def calcular_potencia(forecast_combinado, datos_potencia_historica=None, metodo='ajustada',
                    factor_ajuste=1, factor_suavizado=0.60, frecuencia='mensual'):
    """
    Calcula la potencia basándose en las predicciones de energía.
    Aplica el cálculo a 'yhat' (combinado) y a las columnas yhat individuales si existen.
    """
    if metodo == 'ajustada':
        return calcular_potencia_ajustada(forecast_combinado, factor_suavizado, factor_ajuste, frecuencia) # factor_ajuste es factor_escala

    df = forecast_combinado.copy()
    if 'ds' in df.columns: df['ds'] = pd.to_datetime(df['ds'])
    else: print("Error: 'ds' column missing in forecast for power calculation."); return df
    df = df.sort_values('ds')

    # Determinar horas_periodo
    if frecuencia == 'mensual':
        df['año'] = df['ds'].dt.year; df['mes'] = df['ds'].dt.month
        df['horas_periodo'] = df.apply(lambda r: calendar.monthrange(r['año'],r['mes'])[1]*24, axis=1)
    elif frecuencia == 'diario': df['horas_periodo'] = 24
    elif frecuencia in ['horario', 'sub-horario']: df['horas_periodo'] = 1
    else: # Default mensual
        df['año'] = df['ds'].dt.year; df['mes'] = df['ds'].dt.month
        df['horas_periodo'] = df.apply(lambda r: calendar.monthrange(r['año'],r['mes'])[1]*24, axis=1)

    print(f"Calculando potencia con método {metodo} (simple)...")
    cols_map = [('yhat', 'potencia_combinado'), ('yhat_prophet','potencia_prophet'), ('yhat_rnn','potencia_gru'), ('yhat_avanzado','potencia_wavenet'), ('yhat_gbr','potencia_gbr')]
    for y_col, p_col in cols_map:
        if y_col in df.columns and df[y_col].notna().any():
            df[p_col] = df[y_col] / df['horas_periodo'] * factor_ajuste # factor_ajuste for simple avg
            df[p_col] = df[p_col].clip(lower=0)
        elif y_col in df.columns: # Exists but all NaN
            df[p_col] = np.nan

    drop_aux = ['año', 'mes', 'horas_periodo']; df = df.drop(columns=[c for c in drop_aux if c in df.columns], errors='ignore')
    print(f"Potencia (simple) calculada con factor de ajuste: {factor_ajuste}")
    return df

def calcular_potencia_ajustada(forecast_combinado, factor_suavizado=0.60, factor_escala=1.0, frecuencia='mensual'):
    """
    Calcula la potencia de forma ajustada, considerando la tendencia y suavizado.
    Aplica el cálculo a 'yhat' y a las columnas yhat individuales si existen.
    """
    df = forecast_combinado.copy()
    if 'ds' in df.columns: df['ds'] = pd.to_datetime(df['ds'])
    else: print("Error: 'ds' column missing for adjusted power calculation."); return df
    df = df.sort_values('ds')

    # Determinar horas_periodo
    if frecuencia == 'mensual':
        df['año'] = df['ds'].dt.year; df['mes'] = df['ds'].dt.month
        df['horas_periodo'] = df.apply(lambda r: calendar.monthrange(r['año'],r['mes'])[1]*24, axis=1)
    elif frecuencia == 'diario': df['horas_periodo'] = 24
    elif frecuencia in ['horario', 'sub-horario']: df['horas_periodo'] = 1
    else: # Default mensual
        df['año'] = df['ds'].dt.year; df['mes'] = df['ds'].dt.month
        df['horas_periodo'] = df.apply(lambda r: calendar.monthrange(r['año'],r['mes'])[1]*24, axis=1)
    print("Calculando potencia ajustada...")

    cols_map = [('yhat', 'potencia_combinado'), ('yhat_prophet','potencia_prophet'), ('yhat_rnn','potencia_gru'), ('yhat_avanzado','potencia_wavenet'), ('yhat_gbr','potencia_gbr')]
    temp_cols_for_cleanup = []

    for y_col, p_col in cols_map:
        if y_col in df.columns and df[y_col].notna().any():
            base_p_col = f'{p_col}_base'; diff_pct_col = f'{y_col}_diff_pct'
            temp_cols_for_cleanup.extend([base_p_col, diff_pct_col])
            df[base_p_col] = df[y_col] / df['horas_periodo']
            df[diff_pct_col] = df[y_col].pct_change().fillna(0) # Fill NaN pct_change with 0
            df[p_col] = df[base_p_col].copy() # Initialize

            for i in range(1, len(df)):
                pot_prev = df[p_col].iloc[i-1]
                pot_base_actual = df[base_p_col].iloc[i]
                tendencia_pct = df[diff_pct_col].iloc[i]
                ajuste = max(0.5, min(1.5, 1.0 + tendencia_pct)) # Bound adjustment
                pot_adj_tendencia = pot_base_actual * ajuste
                df.loc[df.index[i], p_col] = (1-factor_suavizado)*pot_adj_tendencia + factor_suavizado*pot_prev
            df[p_col] = df[p_col] * factor_escala
            df[p_col] = df[p_col].clip(lower=0)
        elif y_col in df.columns: # Exists but all NaN
            df[p_col] = np.nan

    drop_aux = ['año', 'mes', 'horas_periodo'] + temp_cols_for_cleanup
    df = df.drop(columns=[c for c in drop_aux if c in df.columns], errors='ignore')
    print(f"Potencia ajustada calculada (suavizado={factor_suavizado}, escala={factor_escala})")
    return df

