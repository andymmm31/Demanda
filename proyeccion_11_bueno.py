                df_for_gbr_cp_features['Date_dt_merge_key'] = pd.to_datetime(df_for_gbr_cp_features['Date']); cp_features_dt_gbr = changepoint_features.copy(); cp_features_dt_gbr['ds'] = pd.to_datetime(cp_features_dt_gbr['ds'])
