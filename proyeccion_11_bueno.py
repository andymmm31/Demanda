def preparar_datos_para_prophet(df, columna_energia, regresores=None, growth_type='linear', frecuencia='mensual'):
    """
    Prepara los datos para su uso con Prophet con cálculo automático de capacidad.
    Adaptado para soportar diferentes frecuencias de datos.

    Args:
        df: DataFrame con los datos.
        columna_energia: Nombre de la columna de energía a usar como target.
        regresores: Lista de nombres de columnas a usar como regresores.
        growth_type: Tipo de crecimiento ('linear' o 'logistic').
        frecuencia: Frecuencia de los datos ('mensual', 'diario', 'horario').

    Returns:
        DataFrame: DataFrame formateado para Prophet.
    """
    df_prophet = df[['Date', columna_energia]].copy()
    df_prophet.columns = ['ds', 'y']

    if growth_type == 'logistic':
        max_value = df_prophet['y'].max()
        cap = max_value * 2 # Default
        if len(df_prophet) > 12:
            if frecuencia == 'mensual': years = (df_prophet['ds'].max() - df_prophet['ds'].min()).days / 365.25
            elif frecuencia == 'diario': years = len(df_prophet) / 365.25
            elif frecuencia in ['horario', 'sub-horario']: years = len(df_prophet) / (365.25 * 24)
            else: years = (df_prophet['ds'].max() - df_prophet['ds'].min()).days / 365.25

            if years > 0:
                start_value, end_value = df_prophet.iloc[0]['y'], df_prophet.iloc[-1]['y']
                if start_value > 0:
                    annual_growth_rate = max(min((end_value / start_value) ** (1 / years) - 1, 0.5), -0.5)
                    cap = max_value * (1 + annual_growth_rate) ** 10
        cap = max(cap, max_value * 1.3)

        if frecuencia == 'mensual' and len(df_prophet) > 24: p_rec, p_ant = 12, 12
        elif frecuencia == 'diario' and len(df_prophet) > 60: p_rec, p_ant = 30, 30
        elif frecuencia in ['horario', 'sub-horario'] and len(df_prophet) > 720: p_rec, p_ant = 360, 360
        else: p_rec, p_ant = len(df_prophet) // 4, len(df_prophet) // 4

        if len(df_prophet) > (p_rec + p_ant):
            recent_trend = df_prophet['y'].iloc[-p_rec:].mean() - df_prophet['y'].iloc[-p_rec-p_ant:-p_rec].mean()
            if recent_trend < 0: cap = min(cap, max_value * 1.2)
        df_prophet['cap'] = cap
        print(f"\nCrecimiento logístico con capacidad: {cap:.2f} (Max histórico: {max_value:.2f}, Ratio: {cap/max_value:.2f}x)")

    if regresores:
        for regresor in regresores:
            if regresor in df.columns: df_prophet[regresor] = df[regresor].values
    return df_prophet

