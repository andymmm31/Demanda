def visualizar_matriz_correlacion_no_lineal(df, metodo='spearman'):
    """
    Visualiza la matriz de correlación usando métodos no lineales

    Args:
        df: DataFrame con los datos
        metodo: Método de correlación ('spearman' o 'kendall')

    Returns:
        DataFrame: Matriz de correlación
    """
    cols_numericas = df.select_dtypes(include=['float64', 'int64']).columns.tolist()
    correlation_matrix = df[cols_numericas].corr(method=metodo)
    plt.figure(figsize=(12, 10))
    plt.title(f'Matriz de Correlación ({metodo.capitalize()})')
    heatmap = plt.pcolor(correlation_matrix, cmap='coolwarm', vmin=-1, vmax=1)
    plt.colorbar(heatmap)
    plt.xticks(np.arange(0.5, len(cols_numericas)), cols_numericas, rotation=90)
    plt.yticks(np.arange(0.5, len(cols_numericas)), cols_numericas)
    for i in range(len(cols_numericas)):
        for j in range(len(cols_numericas)):
            plt.text(i + 0.5, j + 0.5, f'{correlation_matrix.iloc[j, i]:.2f}',
                     ha='center', va='center',
                     color='white' if abs(correlation_matrix.iloc[j, i]) > 0.5 else 'black')
    plt.tight_layout(); plt.show()
    return correlation_matrix

def sugerir_umbral_correlacion(df, target_variable, metodo='spearman'):
    """
    Sugiere umbrales de correlación analizando la distribución de correlaciones

    Args:
        df: DataFrame con los datos
        target_variable: Variable objetivo para la correlación
        metodo: Método de correlación (spearman o kendall)

    Returns:
        tuple: (umbral_alto, umbral_medio, umbral_bajo)
    """
    cols_numericas = df.select_dtypes(include=['float64', 'int64']).columns.tolist()
    cols_numericas = [col for col in cols_numericas if col != target_variable]
    correlaciones = [abs(df[col].corr(df[target_variable], method=metodo)) for col in cols_numericas]
    correlaciones.sort(reverse=True)

    plt.figure(figsize=(12, 6))
    plt.bar(range(len(correlaciones)), correlaciones, alpha=0.7)
    plt.title(f'Distribución de Correlaciones Absolutas con {target_variable}')
    plt.xlabel('Variables (ordenadas por correlación)'); plt.ylabel(f'Correlación Absoluta ({metodo})')
    plt.grid(True, axis='y')

    if len(correlaciones) > 0:
        umbral_alto = max(0.5, np.percentile(correlaciones, 80))
        umbral_medio = max(0.3, np.percentile(correlaciones, 50))
        umbral_bajo = max(0.2, np.percentile(correlaciones, 30))
        plt.axhline(y=umbral_alto, color='r', linestyle='--', label=f'Alto ({umbral_alto:.3f})')
        plt.axhline(y=umbral_medio, color='g', linestyle='--', label=f'Medio ({umbral_medio:.3f})')
        plt.axhline(y=umbral_bajo, color='b', linestyle='--', label=f'Bajo ({umbral_bajo:.3f})')
        plt.legend(); plt.tight_layout(); plt.show()
    else:
        umbral_alto, umbral_medio, umbral_bajo = 0.6, 0.4, 0.2
    return umbral_alto, umbral_medio, umbral_bajo

def identificar_regresores_no_lineales(df, target_variable='Energía', threshold=0.3, metodo='spearman'):
    """
    Identifica variables con correlación significativa que pueden servir como regresores

    Args:
        df: DataFrame con los datos
        target_variable: Variable objetivo para la correlación
        threshold: Umbral de correlación para seleccionar variables
        metodo: Método de correlación (spearman o kendall)

    Returns:
        list: Lista de nombres de variables seleccionadas como regresores
    """
    cols_numericas = df.select_dtypes(include=['float64', 'int64']).columns.tolist()
    cols_numericas = [col for col in cols_numericas if col != target_variable]
    regresores, correlaciones = [], {}
    print(f"\nIdentificando regresores potenciales (umbral = {threshold:.3f})...")
    for col in cols_numericas:
        corr = abs(df[col].corr(df[target_variable], method=metodo))
        correlaciones[col] = corr
        if corr >= threshold: regresores.append(col)

    correlaciones_ordenadas = sorted(correlaciones.items(), key=lambda x: x[1], reverse=True)
    plt.figure(figsize=(12, 8))
    bars = plt.barh([x[0] for x in correlaciones_ordenadas], [x[1] for x in correlaciones_ordenadas], alpha=0.7)
    for i, (var, corr) in enumerate(correlaciones_ordenadas):
        if corr >= threshold: bars[i].set_color('green')
    plt.axvline(x=threshold, color='red', linestyle='--', label=f'Umbral ({threshold:.3f})')
    plt.title(f'Correlación {metodo.capitalize()} con {target_variable}')
    plt.xlabel(f'Correlación Absoluta ({metodo})'); plt.ylabel('Variables')
    plt.legend(); plt.grid(True, axis='x'); plt.tight_layout(); plt.show()

    if regresores:
        print("\nVariables seleccionadas como regresores:")
        for var in regresores: print(f"  - {var} (correlación: {correlaciones[var]:.3f})")
    else:
        print("\nNinguna variable supera el umbral de correlación establecido")
    return regresores

def detectar_cambios_estructurales(df, columna='Energía', ventana=None, umbral_z=2.5, vis_detalle=True, frecuencia='mensual'):
    """
    Detecta cambios estructurales en la serie temporal adaptado a diferentes frecuencias

    Args:
        df: DataFrame con los datos
        columna: Nombre de la columna a analizar
        ventana: Tamaño de ventana para cálculo de medias móviles (se ajusta según frecuencia si es None)
        umbral_z: Umbral de score z para considerar un cambio estructural
        vis_detalle: Si se deben visualizar detalles del análisis
        frecuencia: Frecuencia de los datos ('mensual', 'diario', 'horario', etc.)

    Returns:
        list: Lista con fechas de cambios estructurales detectados
    """
    if ventana is None:
        if frecuencia == 'mensual': ventana = 24
        elif frecuencia == 'diario': ventana = 60
        elif frecuencia in ['horario', 'sub-horario']: ventana = 24 * 7
        else: ventana = 24
    print(f"Usando ventana de {ventana} periodos para detección de cambios estructurales.")

    serie, fechas = df[columna].copy(), df['Date'].copy()
    media_movil = serie.rolling(window=ventana).mean()
    std_movil = serie.rolling(window=ventana).std()
    diff_media = media_movil.diff()
    z_scores = abs(diff_media / (std_movil + 1e-10))
    cambios_potenciales = z_scores > umbral_z
    cambios_idx = np.where(cambios_potenciales)[0]

    if len(cambios_idx) == 0: print("No se detectaron cambios estructurales en la serie"); return []

    cambios_filtrados = [cambios_idx[0]]
    for idx in cambios_idx[1:]:
        if idx - cambios_filtrados[-1] >= ventana: cambios_filtrados.append(idx)
    fechas_cambios = [fechas.iloc[idx] for idx in cambios_filtrados if idx < len(fechas)]

    if vis_detalle:
        plt.figure(figsize=(15, 8))
        plt.subplot(2, 1, 1)
        plt.plot(fechas, serie, 'b-', label='Serie original')
        plt.plot(fechas, media_movil, 'r-', label=f'Media móvil ({ventana} periodos)')
        for fecha_cambio in fechas_cambios:
            plt.axvline(x=fecha_cambio, color='g', linestyle='--')
            plt.text(fecha_cambio, serie.max(), fecha_cambio.strftime('%Y-%m-%d'), rotation=90, verticalalignment='top')
        plt.title('Detección de Cambios Estructurales'); plt.legend(); plt.grid(True)
        plt.subplot(2, 1, 2)
        plt.plot(fechas, z_scores, 'k-', label='Z-scores de cambios')
        plt.axhline(y=umbral_z, color='r', linestyle='--', label=f'Umbral (z={umbral_z})')
        for fecha_cambio in fechas_cambios: plt.axvline(x=fecha_cambio, color='g', linestyle='--')
        plt.title('Z-scores de Cambios en la Media Móvil'); plt.legend(); plt.grid(True)
        plt.tight_layout(); plt.show()

    print(f"\nSe detectaron {len(fechas_cambios)} cambios estructurales:")
    for i, fecha_cambio in enumerate(fechas_cambios): print(f"  {i+1}. {fecha_cambio.strftime('%Y-%m-%d')}")
    return fechas_cambios

def incorporar_cambios_estructurales(df_prophet, fechas_cambios):
    """
    Incorpora los cambios estructurales como variables indicadoras en el DataFrame

    Args:
        df_prophet: DataFrame de Prophet
        fechas_cambios: Lista de fechas con cambios estructurales

    Returns:
        DataFrame: DataFrame con variables indicadoras añadidas
    """
    df_out = df_prophet.copy()
    for i, fecha_cambio in enumerate(fechas_cambios):
        nombre_var = f'cambio_estructural_{i+1}'
        df_out[nombre_var] = (df_out['ds'].ge(fecha_cambio)).astype(int)
        print(f"Variable '{nombre_var}' creada para el cambio en {fecha_cambio.strftime('%Y-%m-%d')}")
    return df_out

