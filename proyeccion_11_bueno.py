def predecir_con_rnn(modelo_info, datos_historicos_energia_input, periodos_futuros=120,
                     estacionalidad_periodos=None, frecuencia='mensual',
                     changepoint_features_futuras=None): # changepoint_features_futuras es opcional
    """
    Realizar predicciones con un modelo de red neuronal (GRU/WaveNet).
    Maneja múltiples features de entrada si el modelo fue entrenado con ellas.
    Añade componente estacional simple a la predicción de la target principal.

    Args:
        modelo_info: Diccionario con modelo y metadatos (scaler, time_steps, n_features_model_input,
                     scaler_n_features_original_fit, scaler_target_idx, feature_names_input).
        datos_historicos_energia_input: Array NumPy 1D con los datos históricos SOLO de la variable energía.
        periodos_futuros: Número de períodos futuros a predecir.
        estacionalidad_periodos: Número de períodos en un ciclo estacional (si es None, se determina por frecuencia).
        frecuencia: Frecuencia de los datos ('mensual', 'diario', 'horario', etc.).
        changepoint_features_futuras: DataFrame opcional con 'ds' y las columnas de CP para el futuro.
                                      Debe cubrir los 'periodos_futuros'. Si se usaron CPs en el entrenamiento.

    Returns:
        array: Array NumPy con predicciones desnormalizadas (solo para la variable energía).
    """
    model = modelo_info['model']
    scaler = modelo_info['scaler'] # Este scaler fue ajustado con todas las features de entrada del modelo
    time_steps = modelo_info['time_steps']
    n_features_model_input = modelo_info['n_features_model_input'] # Num features que el modelo espera en su entrada
    scaler_n_features_original_fit = modelo_info['scaler_n_features_original_fit'] # Num features con las que se ajustó el scaler
    scaler_target_idx = modelo_info['scaler_target_idx'] # Índice de la target (energía) en las features del scaler
    feature_names_original_input = modelo_info.get('feature_names_input', []) # Nombres de features originales

    if estacionalidad_periodos is None:
        estacionalidad_periodos = obtener_estacionalidad(frecuencia)

    print(f"Prediciendo con RNN: time_steps={time_steps}, n_features_input={n_features_model_input}, scaler_target_idx={scaler_target_idx}")

    datos_hist_energia_norm = scaler.transform(
        np.tile(datos_historicos_energia_input.reshape(-1,1), (1, scaler_n_features_original_fit))
    )[:, scaler_target_idx] # Escalar energía y tomar la columna escalada correcta

    # b. Otras features (Changepoints) si el modelo las usó
    historical_features_list_norm = [datos_hist_energia_norm]

    if n_features_model_input > 1 and feature_names_original_input and len(feature_names_original_input) > 1:
        print(f"  RNN usó features adicionales: {feature_names_original_input[1:]}")

        if changepoint_features_futuras is None:
            print("  ADVERTENCIA: Modelo RNN entrenado con CPs, pero `changepoint_features_futuras` no proporcionado. Usando ceros para CPs.")
            for _ in range(1, n_features_model_input): # Llenar con ceros si faltan
                historical_features_list_norm.append(np.zeros_like(datos_hist_energia_norm))
        else:
            if changepoint_features_futuras is not None:
                for i, feat_name in enumerate(feature_names_original_input):
                    if i == scaler_target_idx: continue # Ya tenemos la energía
                    if feat_name in changepoint_features_futuras.columns:
                        # Tomar los valores históricos de esta CP (últimos time_steps)
                        # Esto es complicado porque changepoint_features_futuras es para el futuro.
                        # Necesitaríamos acceso a los datos históricos de CP.
                        # Se omite por ahora, asumiendo que esta función se mejora o que el modelo es univariado.
                        print(f"    Predicción con CP '{feat_name}' no implementada completamente en predecir_con_rnn (requiere CPs históricas).")
                        # Añadir ceros como placeholder para las CPs históricas
                        if len(historical_features_list_norm) < n_features_model_input:
                             historical_features_list_norm.append(np.zeros_like(datos_hist_energia_norm))

    # Si después de todo, no tenemos suficientes columnas de features, rellenar con la energía target replicada
    # Esto solo es un fallback si la preparación de features fue incompleta.
    while len(historical_features_list_norm) < n_features_model_input:
        print(f"  Adv: Rellenando feature faltante {len(historical_features_list_norm)} con energía replicada para RNN.")
        historical_features_list_norm.append(datos_hist_energia_norm) # Replicar energía si faltan CPs

    # Combinar todas las features históricas (ya escaladas)
    all_historical_features_scaled = np.stack(historical_features_list_norm[:n_features_model_input], axis=-1)

    # Secuencia de entrada inicial
    current_input_sequence_scaled = all_historical_features_scaled[-time_steps:].reshape(1, time_steps, n_features_model_input)

    # 2. Componente Estacional (simple, basado en la energía histórica escalada)
    comp_estacional_energia = [
        np.mean(datos_hist_energia_norm[np.arange(i_est, len(datos_hist_energia_norm), estacionalidad_periodos)])
        if len(np.arange(i_est, len(datos_hist_energia_norm), estacionalidad_periodos)) > 0
        else np.mean(datos_hist_energia_norm)
        for i_est in range(estacionalidad_periodos)
    ]
    if len(comp_estacional_energia) < estacionalidad_periodos: # En caso de que datos_hist_energia_norm sea corto
        comp_estacional_energia = [np.mean(datos_hist_energia_norm)] * estacionalidad_periodos

    comp_estacional_energia = np.array(comp_estacional_energia) - np.mean(comp_estacional_energia) # Centrar
    amp_estacional_energia = 0.05 * (np.max(datos_hist_energia_norm) - np.min(datos_hist_energia_norm)) # Amplitud pequeña
    if np.max(np.abs(comp_estacional_energia)) > 1e-9:
         comp_estacional_energia *= (amp_estacional_energia / np.max(np.abs(comp_estacional_energia)))
    else: # Evitar división por cero si no hay varianza estacional
        comp_estacional_energia = np.zeros(estacionalidad_periodos)


    # 3. Bucle de Predicción Iterativa
    predicciones_energia_escaladas = []
    pbar_pred_rnn = get_progress_bar(total=periodos_futuros, desc="Prediciendo RNN", leave=False)

    for i_fut in range(periodos_futuros):
        # Predecir el siguiente paso (todas las features si el modelo es multivariado en salida, pero Dense(1) es univariado)
        pred_siguiente_paso_scaled_target_only = model.predict(current_input_sequence_scaled, verbose=0)[0,0]

        # Añadir componente estacional SOLO a la predicción de energía
        pred_siguiente_energia_con_estacionalidad = pred_siguiente_paso_scaled_target_only + comp_estacional_energia[i_fut % estacionalidad_periodos]
        predicciones_energia_escaladas.append(pred_siguiente_energia_con_estacionalidad)

        nueva_fila_features_scaled = np.zeros(n_features_model_input)
        nueva_fila_features_scaled[scaler_target_idx] = pred_siguiente_energia_con_estacionalidad # Usar la predicción de energía con estacionalidad

        # Para las otras features (CPs), si se usaron:
        if n_features_model_input > 1:
            if changepoint_features_futuras is not None and not changepoint_features_futuras.empty:
                fecha_actual_pred = changepoint_features_futuras['ds'].iloc[i_fut] # Asumiendo que está ordenado
                for k_feat, feat_name_orig in enumerate(feature_names_original_input):
                    if k_feat == scaler_target_idx: continue # Ya manejamos la energía
                    if feat_name_orig in changepoint_features_futuras.columns:
                        try:
                            cp_val_futuro = changepoint_features_futuras.loc[changepoint_features_futuras['ds'] == fecha_actual_pred, feat_name_orig].iloc[0]
                            if np.isnan(cp_val_futuro): cp_val_futuro = 0 # Default si es NaN
                        except IndexError: # Si la fecha no está
                            cp_val_futuro = 0 # O ffill/bfill o última conocida

                        if k_feat < n_features_model_input: # Asegurar que no exceda las features del modelo
                            nueva_fila_features_scaled[k_feat] = cp_val_futuro
                    elif k_feat < n_features_model_input:
                        nueva_fila_features_scaled[k_feat] = 0 # Usar cero
            else: # No hay CPs futuras, llenar con ceros si el modelo espera más features
                 for k_feat_fill in range(n_features_model_input):
                     if k_feat_fill != scaler_target_idx:
                         nueva_fila_features_scaled[k_feat_fill] = 0.0


        # Actualizar la secuencia de entrada
        current_input_sequence_scaled = np.append(current_input_sequence_scaled[:, 1:, :],
                                                  [[nueva_fila_features_scaled]],
                                                  axis=1)
        pbar_pred_rnn.update(1)
    pbar_pred_rnn.close()

    array_para_desnormalizar = np.zeros((len(predicciones_energia_escaladas), scaler_n_features_original_fit))
    array_para_desnormalizar[:, scaler_target_idx] = np.array(predicciones_energia_escaladas).flatten()

    predicciones_energia_desnormalizadas = scaler.inverse_transform(array_para_desnormalizar)[:, scaler_target_idx]

    return predicciones_energia_desnormalizadas.flatten()

def predecir_con_gbr(modelo_info, datos_historicos_energia_input, periodos_futuros=120, frecuencia='mensual',
                     changepoint_features_futuras=None):
    """
    Realizar predicciones con un modelo Gradient Boosting Regressor.
    Maneja si el modelo fue entrenado con datos diferenciados.
    Maneja si el modelo fue entrenado con características de changepoint.
    """
    model = modelo_info['model']
    scaler = modelo_info['scaler']
    time_steps = modelo_info['time_steps']
    usar_diferenciacion = modelo_info.get('usar_diferenciacion', False)
    feature_names_gbr = modelo_info.get('feature_names_input', [])

    print(f"Prediciendo con GBR: time_steps={time_steps}, diferenciación={usar_diferenciacion}")
    if feature_names_gbr: print(f"  GBR usó features: ~{len(feature_names_gbr)} (ej: {feature_names_gbr[:min(3, len(feature_names_gbr))]})")

    datos_hist_energia_orig = datos_historicos_energia_input.copy().astype(float)
    predicciones_absolutas_desnormalizadas = []

    # 1. Preparar la secuencia de entrada inicial para GBR
    # a. Lags de Energía (diferenciada o no, y escalada)
    current_energy_series_for_lags = None
    if usar_diferenciacion:
        if len(datos_hist_energia_orig) < 2:
            print("  GBR Error: datos históricos de energía insuficientes para diferenciar."); return np.full(periodos_futuros, np.nan)
        current_energy_series_for_lags = np.diff(datos_hist_energia_orig)
    else:
        current_energy_series_for_lags = datos_hist_energia_orig

    if len(current_energy_series_for_lags) < time_steps:
        print(f"  GBR Error: datos procesados ({len(current_energy_series_for_lags)}) insuficientes para time_steps ({time_steps})."); return np.full(periodos_futuros, np.nan)

    scaled_energy_for_lags = scaler.transform(current_energy_series_for_lags.reshape(-1,1)).flatten()
    current_energy_lags_scaled = scaled_energy_for_lags[-time_steps:]

    # b. Lags de Changepoint Features (si se usaron)
    num_cp_features_used_by_gbr = 0
    historical_cp_lags_list = []
    cp_cols_in_future_df = [] # Definir fuera del if para que exista si se usa después

    if feature_names_gbr and len(feature_names_gbr) > time_steps:
        num_total_lag_features = len(feature_names_gbr)
        if num_total_lag_features > 0 and time_steps > 0 and num_total_lag_features % time_steps == 0: # Evitar división por cero
            num_base_features_incl_energy = num_total_lag_features // time_steps
            num_cp_features_used_by_gbr = num_base_features_incl_energy - 1

            if num_cp_features_used_by_gbr > 0 and changepoint_features_futuras is not None:
                print(f"  GBR usó {num_cp_features_used_by_gbr} feature(s) de changepoint.")
                cp_cols_in_future_df = [col for col in changepoint_features_futuras.columns if col != 'ds']

                for i_cp_gbr in range(min(num_cp_features_used_by_gbr, len(cp_cols_in_future_df))):
                    cp_name_gbr = cp_cols_in_future_df[i_cp_gbr]
                    if cp_name_gbr in changepoint_features_futuras.columns:
                        print(f"    Obtención de lags históricos para CP '{cp_name_gbr}' en predecir_con_gbr es un placeholder.")
                        historical_cp_lags_list.append(np.zeros(time_steps)) # Placeholder
                    else:
                         historical_cp_lags_list.append(np.zeros(time_steps))
            elif num_cp_features_used_by_gbr > 0 and changepoint_features_futuras is None:
                print(f"  GBR esperaba {num_cp_features_used_by_gbr} CPs, pero changepoint_features_futuras no se proporcionó. Usando ceros para CPs.")
                for _ in range(num_cp_features_used_by_gbr):
                    historical_cp_lags_list.append(np.zeros(time_steps))


    # ---> INICIO DE LA CORRECCIÓN DE INDENTACIÓN <---
    # Construir la secuencia de entrada inicial completa para GBR
    current_gbr_input_list = [current_energy_lags_scaled] # Esta línea y las siguientes deben estar al mismo nivel
    for cp_lag_seq in historical_cp_lags_list:
        current_gbr_input_list.append(cp_lag_seq)

    current_gbr_input_seq_flat = np.concatenate(current_gbr_input_list).flatten()
    # ---> FIN DE LA CORRECCIÓN DE INDENTACIÓN <---

    # 2. Bucle de Predicción Iterativa
    last_actual_value_for_diff_recon = datos_hist_energia_orig[-1] if usar_diferenciacion else None
    pbar_pred_gbr = get_progress_bar(total=periodos_futuros, desc="Prediciendo GBR", leave=False)

    for i_fut_gbr in range(periodos_futuros):
        input_for_gbr_prediction = current_gbr_input_seq_flat.reshape(1, -1)

        if hasattr(model, 'n_features_in_') and input_for_gbr_prediction.shape[1] != model.n_features_in_:
            # ... (lógica de padding/truncating como antes) ...
            # print(f"  GBR Error Pred: Discrepancia de features. Modelo espera {model.n_features_in_}, input tiene {input_for_gbr_prediction.shape[1]}. Rellenando/truncando.")
            if input_for_gbr_prediction.shape[1] < model.n_features_in_:
                padding = np.zeros((1, model.n_features_in_ - input_for_gbr_prediction.shape[1]))
                input_for_gbr_prediction = np.concatenate([input_for_gbr_prediction, padding], axis=1)
            else:
                input_for_gbr_prediction = input_for_gbr_prediction[:, :model.n_features_in_]

        pred_siguiente_scaled = model.predict(input_for_gbr_prediction)[0]
        pred_siguiente_unscaled = scaler.inverse_transform(np.array([[pred_siguiente_scaled]]))[0,0]

        pred_siguiente_absoluta = 0.0
        if usar_diferenciacion:
            pred_siguiente_absoluta = last_actual_value_for_diff_recon + pred_siguiente_unscaled
            last_actual_value_for_diff_recon = pred_siguiente_absoluta
        else:
            pred_siguiente_absoluta = pred_siguiente_unscaled

        predicciones_absolutas_desnormalizadas.append(pred_siguiente_absoluta)

        new_energy_lags_scaled = np.append(current_energy_lags_scaled[1:], pred_siguiente_scaled)
        current_energy_lags_scaled = new_energy_lags_scaled

        new_cp_lags_list_updated = []
        if num_cp_features_used_by_gbr > 0 and changepoint_features_futuras is not None and i_fut_gbr < len(changepoint_features_futuras): # Asegurar que i_fut_gbr esté en rango
            # fecha_pred_actual_cp = changepoint_features_futuras['ds'].iloc[i_fut_gbr] # Esto puede dar error si i_fut_gbr > len

            for i_cp_update in range(num_cp_features_used_by_gbr):
                # Obtener el nombre de la CP que corresponde a esta iteración
                # Esto asume que cp_cols_in_future_df se llenó correctamente antes
                if i_cp_update < len(cp_cols_in_future_df):
                    cp_name_update = cp_cols_in_future_df[i_cp_update]
                    try:
                        # Obtener el valor de la CP para la fecha futura i_fut_gbr
                        cp_val_futuro_update = changepoint_features_futuras[cp_name_update].iloc[i_fut_gbr]
                        if np.isnan(cp_val_futuro_update): cp_val_futuro_update = 0
                    except (IndexError, KeyError):
                        cp_val_futuro_update = 0

                    current_cp_lag_seq_to_update = historical_cp_lags_list[i_cp_update]
                    new_cp_lag_seq = np.append(current_cp_lag_seq_to_update[1:], cp_val_futuro_update)
                    historical_cp_lags_list[i_cp_update] = new_cp_lag_seq
                    new_cp_lags_list_updated.append(new_cp_lag_seq)
                else: # No hay nombre de CP correspondiente, usar ceros
                    new_cp_lags_list_updated.append(np.zeros(time_steps)) # Placeholder
        elif num_cp_features_used_by_gbr > 0 : # Si se esperaban CPs pero no hay futuras
            for _ in range(num_cp_features_used_by_gbr):
                new_cp_lags_list_updated.append(np.zeros(time_steps))


        updated_gbr_input_list = [current_energy_lags_scaled]
        for cp_lag_seq_upd in new_cp_lags_list_updated:
             updated_gbr_input_list.append(cp_lag_seq_upd)
        current_gbr_input_seq_flat = np.concatenate(updated_gbr_input_list).flatten()

        pbar_pred_gbr.update(1)
    pbar_pred_gbr.close()

    return np.array(predicciones_absolutas_desnormalizadas).flatten()

def crear_modelo_gru_avanzado(input_shape, n_features=1,
                              gru_units=[64, 64],
                              dense_units=[32],
                              dropout_rate=0.2,
                              bidirectional=True,
                              use_attention=False,
                              attention_heads=4,
                              activation_gru='tanh',
                              activation_dense='relu',
                              optimizer_type='adam', learning_rate=0.001,
                              loss_function='mse'):
    """
    Crear un modelo GRU avanzado más configurable.
    """
    inputs = Input(shape=input_shape)
    x = inputs

    for i, units in enumerate(gru_units):
        # La última capa GRU debe retornar secuencias si use_attention es True
        # y la atención se aplica después de todas las capas GRU.
        return_sequences_for_this_layer = (i < len(gru_units) - 1) or use_attention

        if bidirectional:
            x = Bidirectional(GRU(units, return_sequences=return_sequences_for_this_layer, activation=activation_gru))(x)
        else:
            x = GRU(units, return_sequences=return_sequences_for_this_layer, activation=activation_gru)(x)

        if dropout_rate > 0:
            x = Dropout(dropout_rate)(x)

    if use_attention:
        # Verificar si x es una secuencia válida para MHA
        if not (len(x.shape) >=3 and x.shape[1] is not None and x.shape[1] > 0): # x.shape[1] es seq_len
             print("Advertencia: La salida de GRU no es una secuencia válida para MultiHeadAttention. Usando GlobalAveragePooling si es posible.")
             if len(x.shape) >=3 : # Si aún es 3D pero sin seq_len definida (raro)
                 x = GlobalAveragePooling1D()(x)
             # Si ya es 2D, no se puede aplicar MHA directamente sobre la secuencia,
             # ni GAP porque ya está aplanado. La atención se omite efectivamente.
        else: # x es una secuencia
            x_norm = LayerNormalization(epsilon=1e-6)(x)
            # Asegurar que key_dim sea divisible o razonable
            embed_dim = x.shape[-1]
            key_dim_att = embed_dim // attention_heads if embed_dim > 0 and embed_dim % attention_heads == 0 else max(1, embed_dim // 2)

            attention_output = MultiHeadAttention(
                num_heads=attention_heads, key_dim=key_dim_att
            )(query=x_norm, value=x_norm, key=x_norm) # query, value, key son el mismo para self-attention

            x = Add()([x, attention_output]) # Conexión residual
            x = LayerNormalization(epsilon=1e-6)(x)
            x = GlobalAveragePooling1D()(x) # Reducir la secuencia a un vector después de la atención

    for units in dense_units:
        x = Dense(units, activation=activation_dense)(x)
        if dropout_rate > 0:
            x = Dropout(dropout_rate)(x)

    outputs = Dense(1)(x) # Salida para regresión (1 neurona, sin activación lineal por defecto)
    model = Model(inputs=inputs, outputs=outputs)

    # Selección de Optimizador
    if optimizer_type.lower() == 'adam':
        optimizer = Adam(learning_rate=learning_rate)
    elif optimizer_type.lower() == 'adamw':
        optimizer = AdamW(learning_rate=learning_rate)
    elif optimizer_type.lower() == 'rmsprop':
        optimizer = RMSprop(learning_rate=learning_rate)
    else:
        print(f"Optimizador '{optimizer_type}' no reconocido. Usando Adam por defecto.")
        optimizer = Adam(learning_rate=learning_rate)

    # Selección de Función de Pérdida
    if loss_function.lower() == 'mse':
        loss = MeanSquaredError()
    elif loss_function.lower() == 'mae':
        loss = MeanAbsoluteError()
    elif loss_function.lower() == 'huber':
        loss = Huber()
    else:
        print(f"Función de pérdida '{loss_function}' no reconocida. Usando MSE por defecto.")
        loss = MeanSquaredError()

    model.compile(optimizer=optimizer, loss=loss)
    return model

def crear_modelo_wavenet(input_shape, n_features=1,
                         initial_conv_filters=32,
                         residual_block_layers=2,
                         filters_per_block=32,
                         kernel_size=3,
                         dilation_rates=[1, 2, 4, 8, 16],
                         final_conv_filters=64,
                         dense_units=[32],
                         dropout_rate=0.2,
                         activation_conv='relu',
                         activation_dense='relu',
                         optimizer_type='adam', learning_rate=0.001,
                         loss_function='mse'):
    """
    Crear un modelo inspirado en WaveNet más configurable.
    """
    inputs = Input(shape=input_shape)
    # Capa causal inicial para proyectar la entrada al número de filtros deseado
    x = Conv1D(filters=initial_conv_filters, kernel_size=1, padding='causal', activation=activation_conv)(inputs)

    skip_connections_sum = Conv1D(filters=filters_per_block, kernel_size=1, padding='same')(x) # Initialize skip sum with projected input

    for dr in dilation_rates:
        residual_input = x # Guardar la entrada al bloque residual

        # Parte convolucional del bloque
        for _ in range(residual_block_layers):
            # Una arquitectura WaveNet más pura usaría activaciones "gated" (tanh * sigmoid)
            # Aquí se simplifica a una activación estándar después de la convolución.
            x = Conv1D(filters=filters_per_block, kernel_size=kernel_size, padding='causal',
                       dilation_rate=dr, activation=None)(x) # Sin activación aquí, se aplica después de la suma o en la skip
            x = Activation(activation_conv)(x) # Aplicar activación

        # Capa de convolución 1x1 para la salida del skip connection
        skip_out = Conv1D(filters=filters_per_block, kernel_size=1, padding='same', activation=activation_conv)(x)
        skip_connections_sum = Add()([skip_connections_sum, skip_out])

        # Conexión residual: la salida del bloque se suma a la entrada del bloque
        # Asegurar que las dimensiones coincidan para la suma residual
        if residual_input.shape[-1] != x.shape[-1]:
            residual_input = Conv1D(filters=x.shape[-1], kernel_size=1, padding='same')(residual_input)

        x = Add()([residual_input, x]) # Salida del bloque residual, se convierte en entrada para el siguiente

    # Post-procesamiento de la suma de skip connections
    x_processed_skips = Activation(activation_conv)(skip_connections_sum)
    x_processed_skips = Conv1D(filters=final_conv_filters, kernel_size=1, activation=activation_conv)(x_processed_skips)
    x_processed_skips = Activation(activation_conv)(x_processed_skips) # Otra activación

    # Aplanar para las capas densas
    output_flattened = Flatten()(x_processed_skips)

    # Capas densas finales
    x_dense = output_flattened
    for units_d in dense_units:
        x_dense = Dense(units_d, activation=activation_dense)(x_dense)
        if dropout_rate > 0:
            x_dense = Dropout(dropout_rate)(x_dense)

    outputs = Dense(1)(x_dense) # Salida de regresión
    model = Model(inputs=inputs, outputs=outputs)

    # Selección de Optimizador
    if optimizer_type.lower() == 'adam': optimizer = Adam(learning_rate=learning_rate)
    elif optimizer_type.lower() == 'adamw': optimizer = AdamW(learning_rate=learning_rate)
    elif optimizer_type.lower() == 'rmsprop': optimizer = RMSprop(learning_rate=learning_rate)
    else: optimizer = Adam(learning_rate=learning_rate)

    # Selección de Función de Pérdida
    if loss_function.lower() == 'mse': loss = MeanSquaredError()
    elif loss_function.lower() == 'mae': loss = MeanAbsoluteError()
    elif loss_function.lower() == 'huber': loss = Huber()
    else: loss = MeanSquaredError()

    model.compile(optimizer=optimizer, loss=loss)
    return model

def entrenar_modelos_avanzados_continuo(df, modelo_gru_anterior=None, modelo_wavenet_anterior=None, modelo_gbr_anterior=None,
                                      columna='Energía', epocas=100, val_split=0.2,
                                      batch_size=32, id_datos=None, frecuencia='mensual',
                                      usar_diferenciacion_gbr=True,
                                      changepoint_features=None,
                                      config_gru={
                                          'gru_units': [64, 32], 'dense_units': [16], 'dropout_rate': 0.25,
                                          'bidirectional': True, 'use_attention': False, 'attention_heads': 2,
                                          'activation_gru': 'tanh', 'activation_dense': 'relu',
                                          'optimizer_type': 'adam', 'learning_rate': 0.001, 'loss_function': 'huber'
                                      },
                                      config_wavenet={
                                          'initial_conv_filters': 32, 'residual_block_layers': 2,
                                          'filters_per_block': 32, 'kernel_size': 3,
                                          'dilation_rates': [1, 2, 4, 8], 'final_conv_filters': 64,
                                          'dense_units': [32, 16], 'dropout_rate': 0.2,
                                          'activation_conv': 'relu', 'activation_dense': 'relu',
                                          'optimizer_type': 'adam', 'learning_rate': 0.001, 'loss_function': 'huber'
                                      },
                                      config_gbr={
                                          'n_estimators': 800, 'learning_rate': 0.01, 'max_depth': 8,
                                          'min_samples_split': 5, 'min_samples_leaf': 3,
                                          'subsample': 0.7, 'max_features': None,
                                          'loss': 'huber', 'n_iter_no_change': 30, 'tol': 1e-5
                                      },
                                      use_reduce_lr_plateau=True,
                                      early_stopping_patience=25,
                                      disable_tqdm_callback_keras=False
                                     ):
    """
    Entrena modelos avanzados (GRU, WaveNet, GBR).
    Time_steps se calcula internamente.
    Manejo de aprendizaje continuo para Keras: crea nueva instancia, carga pesos.
    """
    # --- Definición de TqdmCallback (Simplificada) ---
    class TqdmCallback(tf.keras.callbacks.Callback):
        def __init__(self, epochs, desc="Entrenamiento", position=1):
            super(TqdmCallback, self).__init__()
            self.epochs = epochs; self.desc = desc; self.position = position; self.pbar = None
        def on_train_begin(self, logs=None):
            self.pbar = get_progress_bar(total=self.epochs, desc=self.desc, position=self.position, leave=False)
        def on_epoch_end(self, epoch, logs=None):
            logs = logs or {}
            loss_val = logs.get('loss'); val_loss_val = logs.get('val_loss'); postfix_str = ""
            if loss_val is not None:
                try: postfix_str += f"loss: {float(loss_val):.4f}"
                except: pass
            if val_loss_val is not None:
                try: postfix_str += f"{' - ' if postfix_str else ''}val_loss: {float(val_loss_val):.4f}"
                except: pass
            if self.pbar:
                if postfix_str: self.pbar.set_postfix_str(postfix_str)
                self.pbar.update(1)
        def on_train_end(self, logs=None):
            if self.pbar: self.pbar.close(); self.pbar = None

    # --- Cálculo Interno y Ajuste de Time Steps ---
    time_steps_calculado = 0
    if frecuencia == 'mensual': ts_adj = min(max(12, len(df)//4), 48)
    elif frecuencia == 'diario': ts_adj = min(max(30, len(df)//4), 120)
    elif frecuencia in ['horario', 'sub-horario']: ts_adj = min(max(72, len(df)//4), 24*7*3)
    else: ts_adj = min(24, len(df)//3)

    min_data_for_sequences = int((ts_adj / (1-val_split)) * 1.1) + 2
    if len(df) < min_data_for_sequences:
        time_steps_calculado = max(1, int(len(df) * (1-val_split) * 0.10))
    else:
        max_allowable_ts = int(len(df) * (1 - val_split) * 0.6) -1
        time_steps_calculado = max(1, min(ts_adj, max_allowable_ts))
    print(f"Time steps calculado internamente para {frecuencia}: {time_steps_calculado}")

    if not os.path.exists('modelos_avanzados'):
        os.makedirs('modelos_avanzados')

    # --- Preparación de Datos para RNNs (GRU/WaveNet) ---
    # Esta sección prepara los datos para los modelos de redes neuronales,
    # incluyendo la adición de características de puntos de cambio (changepoints) si están disponibles.
    features_list_rnn = [df[columna].values.copy().astype(float)]
    feature_names_rnn = [columna]
    n_features_input_rnn = 1
    if changepoint_features is not None and not changepoint_features.empty:
        print("  Incorporando CPs a modelos RNN.")
        df_for_rnn_features = df.copy()
        if 'Date' not in df_for_rnn_features.columns and 'ds' in df_for_rnn_features.columns:
            df_for_rnn_features['Date'] = df_for_rnn_features['ds']
        df_for_rnn_features['Date_dt_merge_key'] = pd.to_datetime(df_for_rnn_features['Date'])
        cp_features_dt_rnn = changepoint_features.copy()
        cp_features_dt_rnn['ds'] = pd.to_datetime(cp_features_dt_rnn['ds'])
        df_merged_cp_rnn = pd.merge(df_for_rnn_features, cp_features_dt_rnn, left_on='Date_dt_merge_key', right_on='ds', how='left', suffixes=('', '_cp')).ffill().bfill()
        for cp_col_rnn in changepoint_features.columns:
            if cp_col_rnn != 'ds':
                col_to_check_in_merged = cp_col_rnn
                if col_to_check_in_merged not in df_merged_cp_rnn.columns and f"{cp_col_rnn}_cp" in df_merged_cp_rnn.columns:
                    col_to_check_in_merged = f"{cp_col_rnn}_cp"
                if col_to_check_in_merged in df_merged_cp_rnn.columns:
                    features_list_rnn.append(df_merged_cp_rnn[col_to_check_in_merged].values.astype(float))
                    feature_names_rnn.append(cp_col_rnn)
                    n_features_input_rnn += 1
        print(f"  Features totales para RNN: {n_features_input_rnn}, Nombres: {feature_names_rnn}")

    all_features_array_rnn = np.stack(features_list_rnn, axis=-1)
    scaler_rnn = MinMaxScaler(feature_range=(0, 1))
    data_scaled_rnn_full_input = scaler_rnn.fit_transform(all_features_array_rnn)
    X_rnn_seq, y_rnn_seq_scaled_raw_all_features = crear_dataset_secuencial(data_scaled_rnn_full_input, time_steps_calculado)
    if X_rnn_seq.shape[0] == 0:
        print("No se pudieron crear secuencias para los modelos RNN. Saltando entrenamiento.")
        return {}
    y_rnn_seq_scaled_target = y_rnn_seq_scaled_raw_all_features[:, 0].reshape(-1, 1)

    # --- Preparación de Datos para GBR ---
    # Similar a la preparación de RNN, pero con la opción de usar datos diferenciados.
    data_values_original_energia = df[columna].values.copy().astype(float)
    X_gbr_seq_final, y_gbr_target_scaled_final, scaler_gbr = None, None, None
    gbr_feature_names_constructed = []
    gbr_target_is_diff = False
    base_energy_for_gbr_lags = np.diff(data_values_original_energia) if usar_diferenciacion_gbr and len(data_values_original_energia) >= 2 else data_values_original_energia
    scaler_gbr = MinMaxScaler(feature_range=(0, 1))
    scaled_energy_for_gbr_lags = scaler_gbr.fit_transform(base_energy_for_gbr_lags.reshape(-1, 1))
    gbr_target_is_diff = usar_diferenciacion_gbr and len(data_values_original_energia) >= 2

    if len(scaled_energy_for_gbr_lags) > time_steps_calculado:
        X_gbr_energy_lags_3d, y_gbr_target_scaled_final = crear_dataset_secuencial(scaled_energy_for_gbr_lags, time_steps_calculado)
        if X_gbr_energy_lags_3d.shape[0] > 0:
            num_gbr_samples = X_gbr_energy_lags_3d.shape[0]
            X_gbr_features_list_final = [X_gbr_energy_lags_3d.reshape(num_gbr_samples, -1)]
            for i in range(time_steps_calculado):
                gbr_feature_names_constructed.append(f"{columna}{'_diff' if gbr_target_is_diff else ''}_lag{i+1}")

            if changepoint_features is not None and not changepoint_features.empty:
                df_for_gbr_cp_features = df.copy()
                if 'Date' not in df_for_gbr_cp_features.columns and 'ds' in df_for_gbr_cp_features.columns:
                    df_for_gbr_cp_features['Date'] = df_for_gbr_cp_features['ds']
                df_for_gbr_cp_features['Date_dt_merge_key'] = pd.to_datetime(df_for_gbr_cp_features['Date'])
                cp_features_dt_gbr = changepoint_features.copy()
                cp_features_dt_gbr['ds'] = pd.to_datetime(cp_features_dt_gbr['ds'])
                df_merged_cp_gbr = pd.merge(df_for_gbr_cp_features, cp_features_dt_gbr, left_on='Date_dt_merge_key', right_on='ds', how='left', suffixes=('', '_cp')).ffill().bfill()
                for cp_col in changepoint_features.columns:
                    if cp_col != 'ds':
                        col_to_check = cp_col if cp_col in df_merged_cp_gbr.columns else f"{cp_col}_cp"
                        if col_to_check in df_merged_cp_gbr.columns:
                            cp_data_series = df_merged_cp_gbr[col_to_check].values.astype(float)
                            if len(cp_data_series) > time_steps_calculado:
                                X_cp_lags, _ = crear_dataset_secuencial(cp_data_series.reshape(-1, 1), time_steps_calculado)
                                if X_cp_lags.shape[0] >= num_gbr_samples:
                                    X_gbr_features_list_final.append(X_cp_lags[-num_gbr_samples:].reshape(num_gbr_samples, -1))
                                    for i in range(time_steps_calculado):
                                        gbr_feature_names_constructed.append(f"{cp_col}_lag{i+1}")

            if X_gbr_features_list_final:
                X_gbr_seq_final = np.concatenate(X_gbr_features_list_final, axis=1)
                print(f"  Forma final de datos GBR (target_diff={gbr_target_is_diff}): X={X_gbr_seq_final.shape}, y={y_gbr_target_scaled_final.shape}")
        else:
            X_gbr_seq_final = None

    # --- División Train/Val ---
    X_train_rnn, X_val_rnn, y_train_rnn, y_val_rnn = [None]*4
    if X_rnn_seq is not None and X_rnn_seq.shape[0] > 0:
        split_idx_rnn = int(X_rnn_seq.shape[0] * (1 - val_split))
        if split_idx_rnn > 0 and X_rnn_seq.shape[0] - split_idx_rnn > 0:
            X_train_rnn, X_val_rnn = X_rnn_seq[:split_idx_rnn], X_rnn_seq[split_idx_rnn:]
            y_train_rnn, y_val_rnn = y_rnn_seq_scaled_target[:split_idx_rnn], y_rnn_seq_scaled_target[split_idx_rnn:]
        else:
            print("  La división Train/Val para RNN resultó en un conjunto vacío. No se entrenarán modelos RNN.")
            X_rnn_seq = None

    X_train_gbr, X_val_gbr, y_train_gbr_flat, y_val_gbr_target_scaled_flat = [None]*4
    if X_gbr_seq_final is not None and y_gbr_target_scaled_final is not None and X_gbr_seq_final.shape[0] == y_gbr_target_scaled_final.shape[0] and X_gbr_seq_final.shape[0] > 0:
        split_idx_gbr = int(X_gbr_seq_final.shape[0] * (1 - val_split))
        if split_idx_gbr > 0 and X_gbr_seq_final.shape[0] - split_idx_gbr > 0:
            X_train_gbr, X_val_gbr = X_gbr_seq_final[:split_idx_gbr], X_gbr_seq_final[split_idx_gbr:]
            y_train_gbr_flat = y_gbr_target_scaled_final[:split_idx_gbr].ravel()
            y_val_gbr_target_scaled_flat = y_gbr_target_scaled_final[split_idx_gbr:].ravel()
        else:
            print("  La división Train/Val para GBR resultó en un conjunto vacío. No se entrenará GBR.")
            X_gbr_seq_final = None
    else:
        print("  Error de alineación o datos vacíos para GBR. No se entrenará GBR.")
        X_gbr_seq_final = None

    keras_callbacks_base = [EarlyStopping(monitor='val_loss', patience=early_stopping_patience, restore_best_weights=True)]
    if use_reduce_lr_plateau:
        keras_callbacks_base.append(ReduceLROnPlateau(monitor='val_loss', factor=0.2, patience=max(1, int(early_stopping_patience/2)-2), min_lr=1e-7, verbose=0))

