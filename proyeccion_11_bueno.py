    """
    Entrena modelos avanzados (GRU, WaveNet, GBR).
    Time_steps se calcula internamente.
    Manejo de aprendizaje continuo para Keras: crea nueva instancia, carga pesos.
    """
    # --- Definición de TqdmCallback (Simplificada) ---
    class TqdmCallback(tf.keras.callbacks.Callback):
        def __init__(self, epochs, desc="Entrenamiento", position=1):
            super(TqdmCallback, self).__init__()
            self.epochs = epochs; self.desc = desc; self.position = position; self.pbar = None
        def on_train_begin(self, logs=None):
            self.pbar = get_progress_bar(total=self.epochs, desc=self.desc, position=self.position, leave=False)
        def on_epoch_end(self, epoch, logs=None):
            logs = logs or {}
            loss_val = logs.get('loss'); val_loss_val = logs.get('val_loss'); postfix_str = ""
            if loss_val is not None:
                try: postfix_str += f"loss: {float(loss_val):.4f}"
                except: pass
            if val_loss_val is not None:
                try: postfix_str += f"{' - ' if postfix_str else ''}val_loss: {float(val_loss_val):.4f}"
                except: pass
            if self.pbar:
                if postfix_str: self.pbar.set_postfix_str(postfix_str)
                self.pbar.update(1)
        def on_train_end(self, logs=None):
            if self.pbar: self.pbar.close(); self.pbar = None

